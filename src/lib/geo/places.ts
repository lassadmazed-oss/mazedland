/** The centre of an annonce's délégation, however it was typed; null when it has none or none known. */
export function delegationCenter(gov: string | null | undefined, del: string | null | undefined): LatLng | null {
  const name = canonicalDelegation(gov, del);
  const c = gov && name ? CENTRES[`${gov}|${name}`] : undefined;
  return c ? { lat: c[0], lng: c[1] } : null;
}

/**
 * Whether a point is clearly outside a governorate: beyond its bounds and a
 * margin of about 2 km. Bounds hold more than the governorate, so this only
 * catches a pin in the wrong town — the picker warns, it does not refuse.
 */
export function outsideGovernorate(gov: string | null | undefined, p: LatLng, margin = 0.02): boolean {
  const b = gov ? GOVERNORATE_BOUNDS[gov] : undefined;
  if (!b) return false;
  return p.lat < b[0] - margin || p.lng < b[1] - margin || p.lat > b[2] + margin || p.lng > b[3] + margin;
}
